import pandas as pd
import numpy as np

"""### Cause of death dataset"""

df = pd.read_csv("Cause_of_death.csv", sep=';', header=1, engine='python', on_bad_lines='warn')

cols_to_fix = ['2014', '2015', '2016', '2017','2018', '2019', '2020', '2021', '2022', '2023', '2024']

for col in cols_to_fix:
    df[col] = pd.to_numeric(df[col].astype(str).str.replace('­­', '', regex=False).str.replace(',', '', regex=False), errors='coerce')

df_long = pd.melt(df, id_vars=['Measure', 'Diagnos', 'Region', 'Sex'],
                      value_vars=cols_to_fix,
                      var_name='Year',
                      value_name='Number of Deaths')

df_long['Year'] = pd.to_numeric(df_long['Year'])

display(df_long.head())

df_long_filtered = df_long[(df_long['Diagnos'])=='All causes of death']
df_long_filtered.head()

yearly_by_group = df_long_filtered.groupby(['Year', 'Sex'])['Number of Deaths'].sum().reset_index()

yearly_by_group

"""### Population size dataset"""

df_population = pd.read_csv("Population_Sweden.csv", sep=';', header=0, engine='python', on_bad_lines='warn', encoding='latin1')
df_population.head()

df_population_long = pd.melt(df_population, id_vars=['region', 'marital status', 'sex'],
                      value_vars= df_population.columns[3:],
                      var_name='Year',
                      value_name='Population size')

df_population_long = df_population_long.drop(columns=['marital status'])

df_population_long = df_population_long.rename(columns={'region': 'Region', 'sex': 'Sex'})

df_population_long = df_population_long.groupby(['Year', 'Region', 'Sex']).sum().reset_index()

df_population_long.head()

# Function to clean region names in df_population_long
def clean_region_name(region):
    if isinstance(region, str):
        # To remove the numeric prefix and ' county'
        cleaned_name = region.split(' ', 1)[-1].replace(' county', '')
        return cleaned_name
    return region

# Apply the cleaning function to the 'Region' column
df_population_long['Region'] = df_population_long['Region'].apply(clean_region_name)

# Explicitly rename 'Götaland' to 'Västra Götaland' to match df_long
df_population_long['Region'] = df_population_long['Region'].replace({'Götaland': 'Västra Götaland'})

df_long_cleaned = df_long.dropna(subset=['Region'])

# To reset sex to be lower case
df_long_cleaned['Sex'] = df_long_cleaned['Sex'].str.lower()

# To standardize 'Sex' column in df_long_cleaned to match df_population_long
df_long_cleaned.loc[:, 'Sex'] = df_long_cleaned['Sex'].replace({'woman': 'women'})

# Ensure the 'Year' column in df_population_long is numeric
df_population_long['Year'] = pd.to_numeric(df_population_long['Year'], errors='coerce')

# Perform the merge operation again with cleaned data
df_merged = pd.merge(df_long_cleaned, df_population_long, on=['Year', 'Region', 'Sex'], how='left')

df_filtered = df_merged[
    (df_merged['Diagnos'] == 'All causes of death') &
    (df_merged['Measure'] == 'Number of deaths')
]

df_filtered.head()

#Aggregate data by sex and year for mortality rate
mortality_rate_group = df_filtered.groupby(['Sex','Year']).agg({
    'Number of Deaths': 'sum',
    'Population size': 'sum'
}).reset_index()

mortality_rate_group.head()

#Mortality rate column (per 1000)
mortality_rate_group['Mortality rate'] = mortality_rate_group['Number of Deaths']/mortality_rate_group['Population size']*1000

mortality_rate_group.head()

"""### Prepare data for ranking causes of death"""

df_causes = df_merged[
    (df_merged['Diagnos'] != 'All causes of death') &
    (df_merged['Measure'] == 'Number of deaths')
]

df_causes.head()

#Causes of death for year 2019

deaths_2019 = df_causes[df_causes['Year'] == 2019]

# Group by 'Diagnos' and sum the 'Number of Deaths'
top_causes_2019 = deaths_2019.groupby('Diagnos')['Number of Deaths'].sum().reset_index()

# Sort in descending order to see the top causes
top_causes_2019 = top_causes_2019.sort_values(by='Number of Deaths', ascending=False)

top_causes_2019['Year']=2019

#Same for 2020

deaths_2020 = df_causes[df_causes['Year'] == 2020]

top_causes_2020 = deaths_2020.groupby('Diagnos')['Number of Deaths'].sum().reset_index()

top_causes_2020 = top_causes_2020.sort_values(by='Number of Deaths', ascending=False)

top_causes_2020['Year']=2020

#And the same for 2024

deaths_2024 = df_causes[df_causes['Year'] == 2024]

top_causes_2024 = deaths_2024.groupby('Diagnos')['Number of Deaths'].sum().reset_index()

top_causes_2024 = top_causes_2024.sort_values(by='Number of Deaths', ascending=False)

top_causes_2024['Year']=2024

#I need to remove the codes for special purposes as it will show up the same as covid
combined = pd.concat([top_causes_2019, top_causes_2020, top_causes_2024], ignore_index=True)
combined_filtered = combined[~combined['Diagnos'].str.contains('Codes for special purposes', na=False)]

